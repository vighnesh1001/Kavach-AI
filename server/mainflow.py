def node_api_dispatch(state: IncidentState):
    """Final node in the graph. Sends the completed AI analysis to the external FastAPI Dashboard."""


    if not state.get("hazards") or len(state["hazards"]) == 0:
        print(f"⏭️ [NODE: DISPATCH] Event {state['img_id']} was a False Alarm. Skipping Dispatch.")
        return {"status": "Ignored_False_Alarm"}
    print(f"🌐 [NODE: DISPATCH] Sending Event {state['img_id']} to Dashboard...")
    
    def b64_encoder(byte_list):
        if not byte_list: return []
        return [base64.b64encode(b).decode('utf-8') for b in byte_list if b]

    # 3. Encoding Plates and Faces separately
    # Even though they both use the same helper, we keep them in different variables
    encoded_plates = b64_encoder(state.get("license_plates", []))
    encoded_faces = b64_encoder(state.get("detected_faces", []))

    # Change this to your actual running FastAPI URL later
    DASHBOARD_API_URL = "http://127.0.0.1:8000/api/v1/incidents"
    
    # Aligning the payload with your IncidentState keys
    payload = {
        "event_id": state["img_id"],
        "timestamp": state["timestamp"],
        "location": state["geolocation"],
        "license_plates":encoded_plates,
        "detected_faces":encoded_faces,
        "analysis": {
            "hazards": state["hazards"],
            "severity": state.get("severity", "Unknown")
        },
        "routing": {
            "services": state.get("nearest_station", "Pending Dispatch")
        }
    }
    
    try:
        # Using requests.post for clean synchronous execution
        response = requests.post(
            DASHBOARD_API_URL, 
            json=payload,
            timeout=5.0,
            headers={"X-API-Key": "your_secure_hackathon_key"}
        )
        response.raise_for_status()
        print("✅ [NODE: DISPATCH] Dashboard successfully updated.")
        return {"status": "Reported"}
        
    except requests.exceptions.RequestException as e:
        # This will trigger right now because your FastAPI server isn't running yet!
        print(f"⚠️ [NODE: DISPATCH] Could not reach dashboard API: {e}")
        return {"status": "API_Failed"}

def plate_crop_node(state: IncidentState):
    """
    Detects ALL license plates in the frame, crops them, 
    and saves them as an Optional List of bytes in the state.
    """
    # 1. Guard Clause: Don't process if no accident was found
    if not state.get("hazards") or len(state["hazards"]) == 0:
        print("⏭️ [NODE: CROP] No hazards found. Skipping plate extraction.")
        # We return an empty list to keep the state type consistent
        return {"license_plates": [], "status": "Skipped_No_Hazards"}

    print(f"✂️ [NODE: CROP] Extracting all plates for {state['img_id']}...")

    # 2. Decode the frame from state bytes
    nparr = np.frombuffer(state['frame'], np.uint8)
    img = cv2.imdecode(nparr, cv2.IMREAD_COLOR)

    if img is None:
        print("❌ [NODE: CROP] Decoding failed.")
        return {"status": "Error: Decoding Failed"}

    # 3. Run Inference
    results = license_model.predict(source=img, save=False, conf=0.25, verbose=False)

    # 4. Process ALL detected plates into a list
    all_plate_crops = []
    
    # Get image dimensions for safe cropping
    h, w = img.shape[:2]

    for result in results:
        # Loop through every detected box (multiple vehicles)
        for box in result.boxes:
            # Extract coordinates
            x1, y1, x2, y2 = map(int, box.xyxy[0])

            # Safety check: Ensure coordinates are within the image frame
            x1, y1 = max(0, x1), max(0, y1)
            x2, y2 = min(w, x2), min(h, y2)

            # --- CROP ---
            cropped_plate = img[y1:y2, x1:x2]
            
            # Skip if the crop is empty/invalid
            if cropped_plate.size == 0:
                continue

            # --- CONVERT TO BYTES ---
            success, buffer = cv2.imencode('.png', cropped_plate)
            if success:
                all_plate_crops.append(buffer.tobytes())

    # 5. Update the State
    print(f"✅ Successfully cropped {len(all_plate_crops)} license plates.")
    
    return {
        "license_plates": all_plate_crops, 
    }
   
    
    
def face_crop_node(state: IncidentState):
    """
    Detects ALL faces in the frame, crops them, 
    and saves them as an Optional List of bytes.
    """
    # 1. Guard Clause: Skip if no hazard (saves server compute)
    if not state.get("hazards"):
        return {"detected_faces": [], "status": "Skipped_No_Hazards"}

    print(f"👤 [NODE: FACE_CROP] Extracting faces for {state['img_id']}...")

    # 2. Decode the frame
    nparr = np.frombuffer(state['frame'], np.uint8)
    img = cv2.imdecode(nparr, cv2.IMREAD_COLOR)
    if img is None: return {"status": "Error: Decoding Failed"}

    # 3. Run Face Detection Model
    # Ensure face_model is loaded globally: face_model = YOLO("yolov11n-face.pt")
    results = face_model.predict(source=img, save=False, conf=0.30, verbose=False)

    all_face_crops = []
    h, w = img.shape[:2]

    for result in results:
        for box in result.boxes:
            x1, y1, x2, y2 = map(int, box.xyxy[0])

            # Safety Clipping
            x1, y1, x2, y2 = max(0, x1), max(0, y1), min(w, x2), min(h, y2)

            # --- CROP ---
            face_crop = img[y1:y2, x1:x2]
            
            if face_crop.size == 0: continue

            # --- CONVERT TO BYTES ---
            success, buffer = cv2.imencode('.png', face_crop)
            if success:
                all_face_crops.append(buffer.tobytes())

    print(f"✅ Successfully cropped {len(all_face_crops)} faces.")
    
    return {
        "detected_faces": all_face_crops, 
    }



