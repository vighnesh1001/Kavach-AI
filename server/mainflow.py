class IncidentState(TypedDict):
    # Data incoming from Edge (YOLO26n)
    img_id: str
    camera_id: str
    timestamp: str
    geolocation: dict # {'lat': 8.5, 'lon': 76.9}
    frame: bytes      # The actual image data
    
    # Data to be generated by Server (epoch90.pt)
    hazards: List[str]     # ['fire', 'injury', 'major']
    severity: str          # 'critical', 'medium', 'low'
    
    nearest_station: str
    status: str   # 'Received', 'Analyzed', 'Reported', 'Failed'
    license_plates: Optional[List[bytes]]
    detected_faces:Optional[List[bytes]]
    plate_num: Optional[List[str]]       

def initialize_incident(state: IncidentState):
    """Validates the incoming data and sets the initial status."""
    print(f"\n--- [START] Processing Event: {state['img_id']} ---")
    print(f"📍 Location: {state['geolocation']}")
    return {"status": "Received"}

def run_epoch90_analysis(state: IncidentState):
    """Runs the high-accuracy multiclass model on the frame sent from edge."""
    
    # Decode bytes to image
    nparr = np.frombuffer(state['frame'], np.uint8)
    img = cv2.imdecode(nparr, cv2.IMREAD_COLOR)
    
    # Validate decoded image
    if img is None:
        print("❌ ERROR: cv2.imdecode failed — frame bytes are invalid or corrupted")
        return {"hazards": [], "status": "Failed"}
    
    print(f"✅ Image decoded successfully: shape={img.shape}, dtype={img.dtype}")
    print(f"🔧 Model classes available: {server_model.names}")
    
    # Run inference
    results = server_model(img, conf=0.25, verbose=True)
    
    print("-------------------results---------------------------")
    print(f"Number of boxes detected: {len(results[0].boxes)}")
    print(f"Raw boxes: {results[0].boxes}")
    print("-----------------------end---------------------------")
    
    # Parse detections
    found_hazards = []
    for box in results[0].boxes:
        cls_id = int(box.cls[0])
        confidence = float(box.conf[0])
        label = server_model.names[cls_id].lower()
        print(f"   Detected: {label} (conf={confidence:.2f})")
        found_hazards.append(label)
    
    unique_hazards = list(set(found_hazards))
    print("------------------------------------------------")
    print(unique_hazards)
    print("------------------------------------------------")
    
    if not unique_hazards:
        print("⚠️ No hazards detected above confidence threshold.")
    else:
        print(f"🔍 Server Analysis Complete: {unique_hazards}")
    
    return {
        "hazards": unique_hazards,
        "status": "Analyzed"
    }

