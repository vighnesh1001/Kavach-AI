def update_service_node(state: IncidentState):
    """
    Determines which emergency services to notify based on YOLO analysis.
    Logic: 
    - Fire detected -> Add Fire + Police
    - High/Medium/Severe -> Add Police (and potentially Medical)
    """
    print(f"📡 [NODE: SERVICE_ROUTING] Evaluating responders for {state['img_id']}...")
    
    # We'll use a set to avoid duplicate services
    services_to_alert = set()
    hazards = state.get("hazards", [])
    severity = state.get("severity", "Low").lower()

    # 1. THE FIRE RULE
    if "fire" in hazards or "smoke" in hazards:
        services_to_alert.add("Fire Department")
        services_to_alert.add("Police") # Always alert police for fire-related traffic stops

    # 2. THE SEVERITY RULE
    # If it's High, Severe, or Critical, we need Medical and Police
    if any(s in severity for s in ["high", "severe", "critical", "major"]):
        services_to_alert.add("Ambulance/Medical")
        services_to_alert.add("Police")
    
    # 3. THE DEFAULT RULE
    # If a hazard was detected at all, at least the Police should be notified
    if len(hazards) > 0 and not services_to_alert:
        services_to_alert.add("Police")

    # Convert back to a string or list for the state
    service_list = ", ".join(list(services_to_alert)) if services_to_alert else "None (Monitor Only)"
    
    print(f"🚑 Dispatching: {service_list}")
    
    return {
        "nearest_station": service_list,
        "status": "Responders_Identified"
    }
    
